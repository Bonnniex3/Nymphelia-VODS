/** Fallback for characters the font doesn't know: a blank cell the width of a letter. */
const BLANK = new Uint8Array(5);

/** char -> Uint8Array of column masks */
const COLUMNS = new Map();
for (const [ch, rows] of Object.entries(G)) {
  const w = rows[0].length;
  const cols = new Uint8Array(w);
  for (let r = 0; r < DOT_FONT_ROWS; r++) {
    for (let c = 0; c < w; c++) if (rows[r][c] === "#") cols[c] |= 1 << r;
  }
  COLUMNS.set(ch, cols);
}

const IGNORED = /[︎️‍]/; // variation selectors / ZWJ (e.g. "♥️")

/** Column masks for a single character (uppercased); unknown -> blank. */
export function glyphColumns(ch) {
  return COLUMNS.get(ch) || COLUMNS.get(ch.toUpperCase()) || BLANK;
}

/**
 * Lay out `text` in the LED font. Returns a Uint8Array with one 7-bit mask per dot column
 * (bit r = row r lit, row 0 = top), with `gap` blank columns between glyphs.
 *
 *   textToDotColumns("HI") -> [127, 8, 8, 8, 127, 0, 65, 127, 65]
 */
export function textToDotColumns(text = "", gap = 1) {
  const out = [];
  let first = true;
  for (const ch of String(text)) {
    if (IGNORED.test(ch)) continue;
    if (!first) for (let g = 0; g < gap; g++) out.push(0);
    first = false;
    const cols = glyphColumns(ch);
    for (let i = 0; i < cols.length; i++) out.push(cols[i]);
  }
  return Uint8Array.from(out);
}
